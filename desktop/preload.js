const { contextBridge, ipcRenderer } = require('electron');

const EVENTS = ['search:open', 'page:open', 'page:new', 'quick:shown', 'auth:changed', 'gcal:changed', 'team:changed'];

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  isMac: process.platform === 'darwin',
  load: () => ipcRenderer.invoke('data:load'),
  // Sync so a save issued from beforeunload still lands before the window closes.
  save: data => ipcRenderer.sendSync('data:save', data),
  openFromQuickSearch: id => ipcRenderer.send('quick:open', id),
  closeQuickSearch: () => ipcRenderer.send('quick:close'),
  importFiles: () => ipcRenderer.invoke('import:pick'),
  importNotion: () => ipcRenderer.invoke('import:notion'),
  listWorkspaces: () => ipcRenderer.invoke('ws:list'),
  activeWorkspaceName: () => ipcRenderer.invoke('ws:active'),
  createWorkspace: (name, template) => ipcRenderer.invoke('ws:create', { name, template }),
  openWorkspace: id => ipcRenderer.invoke('ws:open', id),
  backToStart: () => ipcRenderer.invoke('ws:back'),
  exportFile: (name, ext, content) => ipcRenderer.invoke('export:save', { name, ext, content }),
  aiStatus: () => ipcRenderer.invoke('ai:status'),
  aiSetKey: (key, model) => ipcRenderer.invoke('ai:setKey', { key, model }),
  aiClearKey: () => ipcRenderer.invoke('ai:clearKey'),
  aiChat: messages => ipcRenderer.invoke('ai:chat', messages),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  authSignIn: () => ipcRenderer.invoke('auth:signIn'),
  authSignOut: () => ipcRenderer.invoke('auth:signOut'),
  authSetConfig: config => ipcRenderer.invoke('auth:setConfig', config),
  authClearConfig: () => ipcRenderer.invoke('auth:clearConfig'),
  gcalStatus: () => ipcRenderer.invoke('gcal:status'),
  gcalConnect: () => ipcRenderer.invoke('gcal:connect'),
  gcalDisconnect: () => ipcRenderer.invoke('gcal:disconnect'),
  gcalList: range => ipcRenderer.invoke('gcal:list', range),
  gcalCreate: (event, calendarId) => ipcRenderer.invoke('gcal:create', { event, calendarId }),
  gcalUpdate: (googleId, event, calendarId) => ipcRenderer.invoke('gcal:update', { googleId, event, calendarId }),
  gcalDelete: (googleId, calendarId) => ipcRenderer.invoke('gcal:delete', { googleId, calendarId }),
  gcalOpen: link => ipcRenderer.send('gcal:open', link),
  teamState: () => ipcRenderer.invoke('team:state'),
  teamRefresh: () => ipcRenderer.invoke('team:refresh'),
  teamCreate: name => ipcRenderer.invoke('team:createTeam', name),
  teamJoin: code => ipcRenderer.invoke('team:joinTeam', code),
  teamSelect: id => ipcRenderer.invoke('team:selectTeam', id),
  teamLeave: () => ipcRenderer.invoke('team:leaveTeam'),
  teamRotateInvite: () => ipcRenderer.invoke('team:rotateInvite'),
  teamRemoveMember: uid => ipcRenderer.invoke('team:removeMember', uid),
  teamSetRole: (uid, role) => ipcRenderer.invoke('team:setRole', uid, role),
  teamCreateTask: input => ipcRenderer.invoke('team:createTask', input),
  teamUpdateTask: (id, patch) => ipcRenderer.invoke('team:updateTask', id, patch),
  teamCreateEvent: input => ipcRenderer.invoke('team:createEvent', input),
  teamUpdateEvent: (id, input) => ipcRenderer.invoke('team:updateEvent', id, input),
  teamDeleteEvent: id => ipcRenderer.invoke('team:deleteEvent', id),
  startDictation: () => ipcRenderer.invoke('voice:start'),
  setTitleBar: (color, symbolColor) => ipcRenderer.send('win:titlebar', { color, symbolColor }),
  on: (channel, fn) => {
    if (EVENTS.includes(channel)) ipcRenderer.on(channel, (_e, ...args) => fn(...args));
  },
});
