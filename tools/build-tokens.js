// Generates desktop/app/tokens.css from folio-handoff/folio-handoff/tokens.json.
// Run: node tools/build-tokens.js
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'folio-handoff/folio-handoff/tokens.json'), 'utf8'));
const out = [];
const block = (selector, vars) => out.push(`${selector} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}`);

out.push('/* GENERATED by tools/build-tokens.js from folio-handoff/folio-handoff/tokens.json. Do not edit by hand. */');

// Template tokens: scoped to the template root, so the app shell is not affected.
for (const [tpl, modes] of Object.entries(tokens.templates)) {
  for (const [mode, vars] of Object.entries(modes)) {
    block(`[data-template="${tpl}"][data-theme="${mode}"]`, vars);
  }
}

// App shell themes. Names follow the shell's own variables (--bg, --side, --card, --fg, --muted, --line, --hover, --accent).
for (const [id, t] of Object.entries(tokens.appThemes)) {
  block(`:root[data-app-theme="${id}"]`, {
    bg: t.bg,
    side: t.side,
    surface: t.surface,
    card: t.card,
    fg: t.text,
    'fg-2': t.text2,
    muted: t.muted,
    line: t.line,
    'line-soft': t.lineSoft,
    hover: t.hover,
    accent: t.accent,
    'accent-ink': t.dark ? '#111111' : '#FFFFFF',
    cover: t.cover,
    sel: t.hover,
  });
}

const file = path.join(root, 'desktop/app/tokens.css');
fs.writeFileSync(file, out.join('\n\n') + '\n');
console.log(`wrote ${path.relative(root, file)} (${out.length} blocks)`);

// The same app themes as plain data for the Appearance modal (the browser cannot read tokens.json).
const data = Object.fromEntries(Object.entries(tokens.appThemes).map(([id, t]) => [id, { name: t.name, mode: t.mode, dark: !!t.dark, bg: t.bg, side: t.side, surface: t.surface, card: t.card, text: t.text, text2: t.text2, muted: t.muted, line: t.line, lineSoft: t.lineSoft, accent: t.accent, cover: t.cover }]));
const dataFile = path.join(root, 'desktop/app/themes-data.js');
fs.writeFileSync(dataFile, `// GENERATED by tools/build-tokens.js. Do not edit by hand.\nwindow.FOLIO_APP_THEMES = ${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${path.relative(root, dataFile)}`);